#!/usr/bin/env node
// The npm CLI (cli/) ships without the configurator source, so it carries its own
// copy of the formatter definitions in cli/data/formatters.js and passes them to
// the generator. That copy was hand-maintained and fell behind: in Nov 2026 it
// still had 20 regex-style `~` badge checks #845 fixed in the configurator, eight
// doubled-star HDR chains, and none of the three Core formatters. This writes the
// configurator's FORMATTERS into it, so CLI builds render the same stream cards.
//
//   node scripts/sync_cli_formatters.mjs          rewrite cli/data/formatters.js
//   node scripts/sync_cli_formatters.mjs --check  exit 1 if it is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(root, 'cli/data/formatters.js');
const { FORMATTERS } = await import(pathToFileURL(resolve(root, 'configurator/src/data/formatters.js')).href);

const body = [
  '// GENERATED by scripts/sync_cli_formatters.mjs from configurator/src/data/formatters.js.',
  '// Do not edit by hand: change the configurator file and re-run the script.',
  `export const FORMATTERS = ${JSON.stringify(FORMATTERS, null, 2)};`,
  '',
].join('\n');

let current = '';
try { current = readFileSync(target, 'utf8'); } catch {}
if (process.argv.includes('--check')) {
  if (current !== body) {
    console.error('cli/data/formatters.js is out of date: run node scripts/sync_cli_formatters.mjs');
    process.exit(1);
  }
  console.log(`cli/data/formatters.js: ${FORMATTERS.length} formatters, up to date`);
} else {
  writeFileSync(target, body);
  console.log(`cli/data/formatters.js: wrote ${FORMATTERS.length} formatters`);
}
