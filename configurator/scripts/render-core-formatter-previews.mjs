#!/usr/bin/env node
/**
 * Render the Core formatter collection through AIOStreams' formatter engine
 * (pinned in UPSTREAM.pin) for one synthetic stream, and write the result to
 * src/data/core-formatter-previews.js for the configurator's cards.
 * The engine is fetched to a temp folder, never committed (it is AGPL).
 *
 *   node scripts/render-core-formatter-previews.mjs          # write
 *   node scripts/render-core-formatter-previews.mjs --check  # exit 1 if stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadFormatterEngine } from '../tests/helpers/aiostreams-formatter-engine.mjs';
import { PREVIEW_SAMPLE } from '../tests/fixtures/core-formatter-samples.mjs';
import { CORE_FORMATTER_STYLES, CORE_SCORE_MODES, buildCoreFormatter } from '../src/data/core-formatters.js';

const OUT = fileURLToPath(new URL('../src/data/core-formatter-previews.js', import.meta.url));

export async function renderPreviews() {
  const { render, parseValue, version } = await loadFormatterEngine();
  const value = parseValue(PREVIEW_SAMPLE);
  const previews = {};
  for (const id of Object.keys(CORE_FORMATTER_STYLES)) {
    previews[id] = {};
    for (const score of CORE_SCORE_MODES) {
      const f = buildCoreFormatter(id, { score });
      previews[id][score] = { n: render(f.name, value), d: render(f.d, value).split('\n') };
    }
  }
  return `// Generated by scripts/render-core-formatter-previews.mjs. Do not edit.\n`
    + `// Rendered by AIOStreams ${version}'s formatter engine for a synthetic sample stream.\n`
    + `export const CORE_PREVIEW_ENGINE_VERSION = ${JSON.stringify(version)};\n`
    + `export const CORE_FORMATTER_PREVIEWS = ${JSON.stringify(previews, null, 2)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = await renderPreviews();
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch {}
    if (current !== next) { console.error('core-formatter-previews.js is stale: run node scripts/render-core-formatter-previews.mjs'); process.exit(1); }
    console.log('core-formatter-previews.js is current');
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${OUT}`);
  }
}
