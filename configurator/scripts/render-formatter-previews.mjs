#!/usr/bin/env node
/**
 * Render every built-in formatter through AIOStreams' formatter engine (pinned
 * in UPSTREAM.pin) for the three compare samples, and write the result to
 * src/data/formatter-previews.js for the side-by-side compare and the cards.
 * Core styles are rendered in each score mode. The engine is fetched to a temp
 * folder, never committed (it is AGPL).
 *
 *   node scripts/render-formatter-previews.mjs          # write
 *   node scripts/render-formatter-previews.mjs --check  # exit 1 if stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadFormatterEngine } from '../tests/helpers/aiostreams-formatter-engine.mjs';
import { COMPARE_SAMPLES } from '../tests/fixtures/core-formatter-samples.mjs';
import { FORMATTERS } from '../src/data/formatters.js';
import { CORE_FORMATTER_STYLES, CORE_SCORE_MODES, buildCoreFormatter } from '../src/data/core-formatters.js';

const OUT = fileURLToPath(new URL('../src/data/formatter-previews.js', import.meta.url));

function renderOne(render, parseValue, f) {
  const out = {};
  for (const s of COMPARE_SAMPLES) {
    const value = parseValue(s.value);
    out[s.key] = { n: render(f.name, value), d: render(f.d, value).split('\n').filter(l => l.trim() !== '') };
  }
  return out;
}

export async function renderFormatterPreviews() {
  const { render, parseValue, version } = await loadFormatterEngine();
  const previews = {};
  const failed = [];
  for (const f of FORMATTERS) {
    try {
      if (CORE_FORMATTER_STYLES[f.id]) {
        previews[f.id] = {};
        for (const score of CORE_SCORE_MODES) previews[f.id][score] = renderOne(render, parseValue, buildCoreFormatter(f.id, { score }));
      } else if (typeof f.name === 'string' && typeof f.d === 'string') {
        previews[f.id] = { default: renderOne(render, parseValue, f) };
      }
    } catch (error) {
      failed.push(`${f.id}: ${error.message}`);
    }
  }
  const samples = COMPARE_SAMPLES.map(({ key, label }) => ({ key, label }));
  return {
    failed,
    source: `// Generated by scripts/render-formatter-previews.mjs. Do not edit.\n`
      + `// Every built-in formatter rendered by AIOStreams ${version}'s formatter engine for three synthetic sample streams.\n`
      + `export const FORMATTER_PREVIEW_ENGINE_VERSION = ${JSON.stringify(version)};\n`
      + `export const FORMATTER_PREVIEW_SAMPLES = ${JSON.stringify(samples)};\n`
      + `export const FORMATTER_PREVIEWS = ${JSON.stringify(previews, null, 1)};\n`,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { source, failed } = await renderFormatterPreviews();
  if (failed.length) console.warn(`not rendered (cards fall back to their illustrative preview):\n  ${failed.join('\n  ')}`);
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(OUT, 'utf8'); } catch {}
    if (current !== source) { console.error('formatter-previews.js is stale: run node scripts/render-formatter-previews.mjs'); process.exit(1); }
    console.log('formatter-previews.js is current');
  } else {
    writeFileSync(OUT, source);
    console.log(`wrote ${OUT}`);
  }
}
